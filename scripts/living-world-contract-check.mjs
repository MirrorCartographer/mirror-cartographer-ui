import assert from 'node:assert/strict';
import fs from 'node:fs';

const world = fs.readFileSync('src/components/LivingWorld.jsx', 'utf8');
const style = fs.readFileSync('src/components/LivingWorld.css', 'utf8');
const entry = fs.readFileSync('src/main.jsx', 'utf8');
const pages = fs.readFileSync('.github/workflows/publish-github-pages.yml', 'utf8');

assert.ok(world.includes("const MEMORY_KEY = 'mc-living-world-visitor-v1'"), 'visitor memory must have a stable local key');
assert.ok(world.includes('visitorId: typeof value.visitorId'), 'each browser visitor must receive a persistent identity');
assert.ok(world.includes('visitorSeed(memory.visitorId)'), 'first encounter must be individualized per visitor');
assert.ok(world.includes('memory.choices.includes'), 'return dialogue must respond to remembered choices');
assert.ok(world.includes('onPointerMove={trackPresence}'), 'the environment must respond to continuous pointer presence');
assert.ok(world.includes("onPresence(nearTazar ? 'tazar-near' : nearJello ? 'jello-near' : 'nearby')"), 'the world must distinguish character proximity');
assert.ok(world.includes("presence === 'tazar-near' && !autoNoticeRef.current.tazar"), 'Tazar must initiate a proximity encounter without a click');
assert.ok(world.includes("presence === 'jello-near' && !autoNoticeRef.current.jello"), 'Jello must initiate an independent proximity encounter');
assert.ok(world.includes('const returningVisitorRef = useRef(memory.visits > 0)'), 'first visits must be distinguished from returning visitors');
assert.ok(world.includes("onPointerLeave={() => onPresence('away')}"), 'the world must register when a visitor leaves the scene');
assert.ok(world.includes("setPresence('still')"), 'stillness must produce a distinct environmental state');
assert.ok(world.includes('function Tazar'), 'Tazar must be a real character component');
assert.ok(world.includes('function Jello'), 'Jello must be a real character component');
assert.ok(world.includes("setDialogue('I keep the doors from getting ideas. They are very ambitious doors.')"), 'clicking Tazar must open a conversation rather than dismiss it');
assert.ok(world.includes('station cat</i></span>'), 'Jello must be visibly named in the scene');
assert.ok(world.includes("speaker === 'JELLO' ? <div className=\"dialogue-choices\""), 'Jello must receive character-specific dialogue choices');
assert.ok(style.includes('.jello-name{'), 'Jello name label must have visible styling');
assert.ok(world.includes('speaking={speaker === "MORROW" && Boolean(dialogue)}'), 'Tazar facial animation must follow active dialogue');
assert.ok(world.includes('speaking={speaker === "JELLO" && Boolean(dialogue)}'), 'Jello facial animation must follow active dialogue');
assert.ok(style.includes('.tazar.speaking .tazar-mouth'), 'Tazar mouth must animate while speaking');
assert.ok(style.includes('.jello.speaking .jello-mouth'), 'Jello mouth must animate while speaking');
assert.ok(world.includes('const toggleSound = async'), 'sound must be an explicit opt-in interaction');
assert.ok(style.includes('.presence-still .tazar-lantern'), 'Tazar must respond to visitor stillness');
assert.ok(style.includes('.presence-still .jello-body'), 'Jello must have an independent stillness animation');
assert.ok(style.includes('.presence-tazar-near .tazar-wings'), 'Tazar must react when approached');
assert.ok(style.includes('.presence-jello-near .jello'), 'Jello must react when approached');
assert.ok(style.includes('.tazar-eyes{translate:var(--gaze-x'), 'Tazar must track the visitor');
assert.ok(style.includes('@media(prefers-reduced-motion:reduce)'), 'motion must respect reduced-motion preferences');
assert.ok(entry.includes(': <LivingWorld />'), 'the Pages default route must open the inhabited world');
assert.ok(pages.includes('npm run build:pages'), 'the hosted build must use the GitHub Pages base path');
assert.ok(pages.includes('actions/upload-pages-artifact@v3'), 'the build must upload a Pages artifact');
assert.ok(pages.includes('actions/deploy-pages@v4'), 'the release must deploy through GitHub Pages');

console.log('PASS: visitor-specific memory, passive presence, character response, accessibility, and GitHub Pages release contract.');
