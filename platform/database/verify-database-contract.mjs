#!/usr/bin/env node
import fs from "node:fs";
const [policyPath, inventoryPath] = process.argv.slice(2);
if (!policyPath || !inventoryPath) process.exit(2);
const p = JSON.parse(fs.readFileSync(policyPath, "utf8"));
const i = JSON.parse(fs.readFileSync(inventoryPath, "utf8"));
const failures = [];
const check = (x,m)=>{if(!x) failures.push(m)};
const digest = x => /^sha256:[0-9a-f]{64}$/.test(x ?? "");

check(i.authority.project_owned, "project database authority required");
check(!i.authority.patroni_authoritative && !i.authority.cloud_database_authoritative, "mechanisms cannot be canonical authority");
check(i.authority.schema_registry_owned && i.authority.migration_ledger_owned, "schema and migration ledger must be project-owned");
check(i.authority.adapter_replaceable, "database adapter must be replaceable");
check(i.topology.nodes.length >= p.topology.minimum_database_nodes, "insufficient database nodes");
check(new Set(i.topology.nodes.map(n=>n.domain)).size >= p.topology.minimum_failure_domains, "insufficient failure domains");
check(i.topology.single_writer, "single-writer topology required");
check(i.topology.synchronous_mode === "strict", "strict synchronous mode required");
check(i.topology.synchronous_node_count >= 1, "synchronous standby required");
check(i.topology.dcs_nodes >= p.topology.quorum_dcs_nodes, "quorum DCS required");
check(i.topology.watchdog && i.topology.fencing, "watchdog and fencing required");
check(!i.topology.application_superuser, "application superuser forbidden");
check(i.durability.data_checksums && i.durability.full_page_writes, "checksums and full-page writes required");
check(i.durability.wal_archiving, "WAL archiving required");
check(i.durability.replication_slots_bounded && i.durability.max_slot_wal_keep_size_mb > 0, "bounded replication slots required");
check(["on","remote_write","remote_apply"].includes(i.durability.critical_sync_commit), "critical transactions require synchronous commit");
check(i.durability.client_override_forbidden, "client durability override forbidden");
check(i.durability.maximum_failover_lag_bytes === 0, "zero-lag failover admission required");
check(i.durability.acknowledged_loss_tested, "acknowledged-loss test required");
check(i.failover.automatic, "automatic failover required");
check(i.failover.manual_operator_count >= 2, "manual failover requires two operators");
check(i.failover.data_loss_override_separate, "data-loss override must be separate");
check(i.failover.timeline_check && i.failover.candidate_lag_check, "timeline and lag checks required");
check(i.failover.old_primary_fenced, "old primary must be fenced");
check(i.failover.pg_rewind && i.failover.fresh_base_backup_fallback, "rewind and fresh-copy fallback required");
check(i.failover.dcs_loss_tested, "DCS loss must be tested");
check(i.migrations.source_controlled && i.migrations.immutable_ids && i.migrations.checksummed, "migration ledger controls required");
check(i.migrations.expand_contract && i.migrations.backward_compatible_window, "expand/contract compatibility required");
check(i.migrations.lock_timeout_ms > 0 && i.migrations.statement_timeout_ms > 0, "migration timeouts required");
check(i.migrations.destructive_operator_count >= 2, "destructive migration requires two operators");
check(i.migrations.backfill_batched && i.migrations.backfill_resumable && i.migrations.backfill_rate_limited, "safe backfill controls required");
check(i.migrations.schema_drift_clear, "schema drift blocks deployment");
check(!i.migrations.down_migration_assumed_safe, "down migrations cannot be assumed safe");
check(!i.logical_migration.ddl_replication_assumed, "logical replication does not carry DDL");
check(!i.logical_migration.sequence_replication_assumed, "logical replication does not carry sequence state");
check(i.logical_migration.schema_applied_before_data, "subscriber schema must precede data");
check(i.logical_migration.replica_identity, "replica identity required");
check(i.logical_migration.source_version >= p.logical_migration.slot_migration_version_floor, "logical slot migration source version too old");
check(i.logical_migration.cutover_write_fence, "cutover write fence required");
check(i.logical_migration.source_retained, "source retained until reconciliation");
check(!i.continuity.original_provider_required && !i.continuity.public_dns_required, "restore must survive provider and public DNS loss");
check(!i.continuity.patroni_required_for_restore, "restore must not require Patroni");
check(i.continuity.cross_implementation_export, "cross-implementation export required");
check(i.continuity.last_clean_host_restore_age_days <= p.continuity.clean_host_restore_max_age_days, "clean-host restore stale");
check(i.continuity.trained_operators >= p.continuity.minimum_trained_operators, "insufficient trained operators");
check(i.evidence.machine_generated && i.evidence.signed, "signed machine evidence required");
check(typeof i.evidence.cluster_system_identifier === "string" && i.evidence.cluster_system_identifier.length > 0, "cluster identity evidence required");
check(Number.isInteger(i.evidence.timeline) && i.evidence.timeline > 0, "timeline evidence required");
check(i.evidence.primary_lsn === i.evidence.replica_flush_lsn, "replica flush LSN must match admitted primary LSN");
check(digest(i.evidence.schema_digest) && digest(i.evidence.migration_ledger_digest), "schema/migration digests required");
check(i.evidence.failover_result, "failover result required");
check(i.evidence.data_loss_bytes === 0, "admitted failover lost acknowledged data");
check(i.evidence.operator_signatures >= 2, "two evidence signatures required");
check(i.evidence.retention_days >= p.evidence.retention_days, "evidence retention insufficient");

if (failures.length) {
  console.error(`REJECT ${failures.length} database invariant(s)`);
  for (const f of failures) console.error(`- ${f}`);
  process.exit(1);
}
console.log("ACCEPT 60 database invariants");
