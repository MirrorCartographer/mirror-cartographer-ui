#!/usr/bin/env python3
import argparse, hashlib, json, pathlib, re
SHA=re.compile(r'^sha256:[0-9a-f]{64}$')
def c(v): return json.dumps(v,sort_keys=True,separators=(',',':')).encode()
def d(v): return 'sha256:'+hashlib.sha256(c(v)).hexdigest()
def stop(m): print(json.dumps({'status':'reject','reason':m},sort_keys=True)); raise SystemExit(1)
def req(x,m):
    if not x: stop(m)
p=argparse.ArgumentParser(); p.add_argument('plan'); a=p.parse_args(); v=json.loads(pathlib.Path(a.plan).read_text())
req(v.get('schema')=='fia.database-failover.v1','schema')
u=dict(v); supplied=u.pop('plan_digest',None); req(supplied==d(u),'plan digest mismatch')
req(v.get('canonical_authority')=='foundation','canonical authority')
db=v.get('database',{}); req(db.get('engine')=='postgresql' and db.get('major_version')==18,'database')
req(db.get('nodes')==3,'database node count'); req(db.get('data_checksums') or db.get('wal_log_hints'),'pg_rewind precondition')
req(db.get('full_page_writes') is True and db.get('wal_archive') is True,'WAL durability')
ha=v.get('ha_controller',{}); req(ha.get('implementation')=='patroni' and ha.get('major_version')==4,'HA controller')
req(ha.get('dcs_members') in (3,5) and ha.get('dcs_failure_domains',0)>=3,'DCS quorum')
req(ha.get('watchdog_mode')=='required' and ha.get('watchdog_safety_margin')==-1,'watchdog')
req(ha.get('check_timeline') is True and ha.get('use_pg_rewind') is True,'timeline/rewind')
req(ha.get('manual_failover_requires_two_operators') is True,'single-person failover')
t=ha.get('timing',{}); lw=t.get('loop_wait',0); rt=t.get('retry_timeout',0); ttl=t.get('ttl',0)
req(lw>0 and rt>0 and ttl>0 and lw+2*rt<=ttl,'invalid Patroni timing')
r=v.get('replication',{}); req(r.get('mode')=='synchronous','asynchronous durability')
req(r.get('patroni_synchronous_mode')=='quorum' and r.get('synchronous_mode_strict') is True,'strict quorum mode')
req(r.get('synchronous_node_count')==1 and r.get('synchronous_commit') in ('on','remote_apply'),'sync policy')
req(0<=r.get('maximum_lag_on_failover_bytes',-1)<=16777216,'lag gate')
req(r.get('application_transactions_may_override_sync') is False,'sync override')
f=v.get('fencing',{}); req(f.get('stonith_required') is True,'STONITH absent')
req(f.get('old_primary_write_path_removed_before_promotion') is True and f.get('fence_ack_required') is True,'fence acknowledgement')
req(f.get('independent_power_or_hypervisor_path') is True and f.get('fence_test_result')=='pass','fence path/drill')
pr=v.get('promotion',{}); req(pr.get('candidate_timeline_verified') is True and pr.get('candidate_lag_verified') is True,'candidate readiness')
req(pr.get('archive_continuity_verified') is True,'archive continuity')
req(pr.get('client_write_probe')=='pass' and pr.get('old_primary_rejected_write_probe')=='pass','split-brain probe')
req(pr.get('receipt_required') is True,'receipt absent')
rec=v.get('recovery',{}); req(rec.get('old_primary_rejoin') in ('pg_rewind-or-rebuild','rebuild-only'),'unsafe rejoin')
req(rec.get('automatic_restart_before_rejoin') is False and rec.get('base_backup_fallback') is True,'rejoin safety')
req(rec.get('restore_drill')=='pass' and rec.get('second_operator') is True,'recovery drill')
metrics=set(v.get('observability',{}).get('required_metrics',[])); needed={'patroni_leader','patroni_dcs_last_seen','patroni_postgres_timeline','replication_replay_lag','replication_sync_state','wal_archive_failures','watchdog_armed','fence_operations','read_write_endpoint_target'}
req(needed.issubset(metrics) and v.get('observability',{}).get('owned_sink') is True,'telemetry')
print(json.dumps({'status':'accept','plan_digest':supplied,'database_nodes':3,'dcs_members':ha['dcs_members']},sort_keys=True))
