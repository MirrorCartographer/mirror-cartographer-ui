#!/usr/bin/env node
import fs from 'node:fs';
const [policyPath='platform/build/policy.json', inventoryPath='platform/build/inventory.json'] = process.argv.slice(2);
const p=JSON.parse(fs.readFileSync(policyPath,'utf8')); const i=JSON.parse(fs.readFileSync(inventoryPath,'utf8'));
const checks=[]; const check=(name,ok)=>checks.push({name,ok:Boolean(ok)});
check('reader normalization',!p.source.reader_normalization_required||i.source.reader_normalization===true);
check('normalized tree digest',!p.source.normalized_tree_digest_required||/^sha256:[a-f0-9]{64}$/.test(i.source.normalized_tree_digest));
check('pinned source commit',!p.source.unpinned_git_forbidden||/^[a-f0-9]{40}$/.test(i.source.source_commit));
check('lockfile',!p.dependencies.lockfile_required||i.dependencies.lockfile==='package-lock.json');
check('frozen install',!p.dependencies.frozen_install_required||i.dependencies.frozen_command==='npm ci');
check('dependency integrity',!p.dependencies.integrity_hashes_required||i.dependencies.integrity_hashes===true);
check('project dependency mirror',!p.dependencies.project_mirror_required||i.dependencies.project_mirror===true);
check('offline build',!p.dependencies.public_registry_during_build_forbidden||i.dependencies.build_network==='none');
check('install scripts constrained',!p.dependencies.install_scripts_default_denied||['deny','allowlist'].includes(i.dependencies.install_scripts));
check('runtime pinned',/^\d+\.\d+\.\d+$/.test(i.toolchain.node));
check('package manager pinned',/^\d+\.\d+\.\d+$/.test(i.toolchain.npm));
check('builder digest pinned',/@sha256:[a-f0-9]{64}$/.test(i.toolchain.builder_image));
check('no host toolchain',i.toolchain.uses_host_toolchain===false);
check('clean workspace',i.execution.clean_workspace===true);
check('fixed locale',i.execution.locale===p.execution.fixed_locale);
check('fixed timezone',i.execution.timezone===p.execution.fixed_timezone);
check('source date epoch',Number.isInteger(i.execution.source_date_epoch));
check('seeded randomness',typeof i.execution.random_seed==='string'&&i.execution.random_seed.length>0);
check('parallelism pinned',Number.isInteger(i.execution.parallelism)&&i.execution.parallelism>0);
check('declared graph inputs',i.graph.declared_inputs_only===true);
check('build graph digest',/^sha256:[a-f0-9]{64}$/.test(i.graph.digest));
check('no undeclared outputs',Array.isArray(i.graph.undeclared_outputs)&&i.graph.undeclared_outputs.length===0);
const builds=i.verification.rebuilds||[]; const digests=new Set(builds.map(x=>x.artifact));
check('independent rebuild quorum',builds.length>=p.verification.independent_rebuilds&&new Set(builds.map(x=>x.worker)).size>=p.verification.independent_rebuilds);
check('byte-identical rebuilds',digests.size===1);
check('artifact sha256',builds.every(x=>/^sha256:[a-f0-9]{64}$/.test(x.artifact)));
check('provenance',i.verification.provenance===true);
check('sbom',i.verification.sbom===true);
check('mirror copies',i.custody.mirror_copies>=p.custody.dependency_mirror_copies);
check('mirror failure domains',new Set(i.custody.failure_domains||[]).size>=p.custody.independent_failure_domains);
check('mirror export',i.custody.exportable===true);
check('hosted registry not sole source',i.custody.hosted_registry_sole_source===false);
for(const c of checks) console.log(`${c.ok?'PASS':'FAIL'} ${c.name}`); const failed=checks.filter(c=>!c.ok);
if(failed.length){console.error(`REJECT ${failed.length} build invariants failed`);process.exit(1)} console.log(`ACCEPT ${checks.length} build invariants`);
