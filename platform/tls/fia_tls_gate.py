#!/usr/bin/env python3
import argparse, hashlib, json, pathlib, re
SHA=re.compile(r'^sha256:[0-9a-f]{64}$'); HTTPS=re.compile(r'^https://')
def c(v): return json.dumps(v,sort_keys=True,separators=(',',':')).encode()
def d(v): return 'sha256:'+hashlib.sha256(c(v)).hexdigest()
def stop(m): print(json.dumps({'status':'reject','reason':m},sort_keys=True)); raise SystemExit(1)
def req(x,m):
    if not x: stop(m)
p=argparse.ArgumentParser(); p.add_argument('plan'); a=p.parse_args(); v=json.loads(pathlib.Path(a.plan).read_text())
req(v.get('schema')=='fia.tls-authority.v1','schema'); u=dict(v); s=u.pop('plan_digest',None); req(s==d(u),'plan digest mismatch')
req(v.get('canonical_authority')=='foundation','authority'); req(v.get('provider') is None,'provider binding')
pub=v.get('public_tls',{}); issuers=pub.get('issuers',[])
req(len(issuers)>=2,'fewer than two public issuers'); req(all(HTTPS.match(i.get('directory_url','')) for i in issuers),'issuer URL')
req(len({i['operator'] for i in issuers})>=2,'issuer operator diversity'); req(all(i.get('account_key_custody')=='foundation' for i in issuers),'account key custody')
req(all(i.get('renewal_test')=='pass' for i in issuers),'renewal test'); req(pub.get('certificate_lifetime_days',0)<=100,'certificate lifetime')
req(pub.get('renew_before_days',0)>=20,'renewal window'); req(pub.get('external_expiry_monitor') is True,'expiry monitor')
req(pub.get('stapling_or_revocation_observation') is True,'revocation observation')
dns=v.get('dns_challenge',{})
if pub.get('challenge')=='dns-01':
    req(dns.get('delegated_zone') is True,'delegated zone'); req(dns.get('credential_scope')=='challenge-zone-only','DNS credential scope')
    req(dns.get('provider_is_not_authority') is True,'DNS provider authority'); req(dns.get('exported_zone_config') is True,'DNS export')
    req(dns.get('second_provider_migration_drill')=='pass','DNS migration drill')
internal=v.get('internal_pki',{})
req(internal.get('implementation')=='step-ca','internal CA'); req(internal.get('offline_root') is True,'online root')
req(internal.get('online_intermediates',0)>=2,'intermediates'); req(internal.get('intermediate_failure_domains',0)>=2,'intermediate domains')
req(internal.get('acme_enabled') is True,'internal ACME'); req(internal.get('short_lived_certificates') is True,'short lived certs')
req(internal.get('root_recovery_quorum',0)>=2,'root quorum'); req(internal.get('root_key_exported_plaintext') is False,'plaintext root key')
req(internal.get('rebuild_drill')=='pass','CA rebuild drill')
r=v.get('runtime',{})
req(r.get('reverse_proxy')=='caddy','proxy'); req(r.get('certificate_storage')=='foundation-owned','certificate storage')
req(r.get('storage_failure_domains',0)>=2,'storage domains'); req(r.get('private_key_mode')=='0600','key permissions')
req(r.get('admin_transport')=='unix-socket','public admin'); req(r.get('multiple_issuers_configured') is True,'issuer failover')
req(r.get('test_ca_first_in_preproduction') is True,'test CA'); req(r.get('clock_sync_monitored') is True,'clock monitoring')
rec=v.get('recovery',{})
req(rec.get('export_format')=='fia.tls-export.v1','export format'); req(rec.get('certificate_inventory') is True,'certificate inventory')
req(rec.get('account_key_inventory') is True,'account key inventory'); req(rec.get('ca_configuration_export') is True,'CA config export')
req(rec.get('offline_copy') is True,'offline copy'); req(SHA.match(rec.get('export_digest','')),'export digest')
req(rec.get('public_ca_failover_drill')=='pass','public CA failover'); req(rec.get('internal_ca_restore_drill')=='pass','internal CA restore')
req(rec.get('second_operator') is True,'second operator')
risk=v.get('risk_controls',{})
req(risk.get('no_on_demand_tls_without_allowlist') is True,'unsafe on-demand TLS'); req(risk.get('renewal_failure_alert_days',0)>=14,'late renewal alert')
req(risk.get('certificate_mismatch_probe') is True,'mismatch probe'); req(risk.get('issuer_chain_probe') is True,'issuer probe')
req(risk.get('domain_control_recovery')=='pass','domain recovery')
print(json.dumps({'status':'accept','plan_digest':s,'public_issuers':len(issuers),'internal_intermediates':internal['online_intermediates']},sort_keys=True))
