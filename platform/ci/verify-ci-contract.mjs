import fs from 'node:fs';
const [policyPath='policy.json', inventoryPath='inventory.json'] = process.argv.slice(2);
const p=JSON.parse(fs.readFileSync(policyPath));
const i=JSON.parse(fs.readFileSync(inventoryPath));
const checks=[]; const need=(ok,msg)=>checks.push([!!ok,msg]);
need(p.authority.project_dispatcher,'project dispatcher');
need(p.authority.hosted_ci_is_adapter_only,'hosted CI adapter only');
need(p.authority.canonical_evidence_project_custody,'project evidence custody');
need(p.workers.ephemeral && p.workers.one_job_max && p.workers.clean_root_per_job,'single-use clean workers');
need(!p.workers.runner_autoupdate && p.workers.pinned_runner_digest,'pinned runner image');
need(new Set(i.failure_domains).size>=p.workers.min_failure_domains,'independent worker failure domains');
need(i.capacity_workers>=p.workers.min_capacity_workers,'minimum worker capacity');
need(p.isolation.microvm_or_equivalent && p.isolation.rootless_job,'strong job isolation');
need(p.isolation.no_host_docker_socket && p.isolation.no_cloud_metadata,'no host socket or metadata exposure');
need(p.isolation.default_network==='deny' && i.job_network==='deny-by-default','deny-default network');
need(p.isolation.resource_limits && p.isolation.workspace_destroyed,'bounded and destroyed workspace');
need(p.supply_chain.actions_pinned_by_commit,'actions pinned by commit');
need(p.supply_chain.toolchain_from_admitted_artifact && p.supply_chain.dependency_mirror_only,'admitted offline toolchain');
need(!p.secrets.fork_jobs_receive_secrets && p.secrets.short_lived_credentials,'secret isolation');
need(p.secrets.credentials_max_minutes<=15 && !p.secrets.release_keys_on_workers,'bounded credentials and no release keys');
need(p.orchestration.test_graph_project_owned && p.orchestration.job_spec_exportable,'owned exportable test graph');
need(p.orchestration.retry_is_new_attempt && p.orchestration.quorum_rebuilds>=2,'auditable retries and rebuild quorum');
need(p.orchestration.fail_closed_on_missing_evidence,'fail closed');
need(p.evidence.signed && p.evidence.external_log_custody,'signed external evidence');
need(p.evidence.records_worker_image_digest && p.evidence.records_source_digest && p.evidence.records_exit_code && p.evidence.records_test_manifest_digest,'complete evidence identity');
need(p.evidence.retention_days>=365,'evidence retention');
need(p.recovery.offline_worker_image && p.recovery.bootstrap_without_public_dns && p.recovery.hosted_ci_not_sole_path,'offline independent recovery');
need(p.recovery.quarterly_clean_host_drill && i.drill_age_days<=92,'fresh recovery drill');
need(p.operations.two_operator_release_jobs,'two-operator release jobs');
need(p.operations.patch_sla_days<=14 && p.operations.critical_patch_sla_hours<=24,'patch deadlines');
need(p.operations.capacity_alerting,'capacity alerting');
need(/^sha256:[0-9a-f]{64}$/.test(i.worker_image),'worker image digest');
need(i.dispatcher==='foundation-ci-dispatcher','canonical dispatcher');
need(i.artifact_source==='project-custody' && i.evidence_store==='project-object-store','project custody endpoints');
const failed=checks.filter(([ok])=>!ok).map(([,m])=>m);
if(failed.length){console.error('REJECT '+failed.join('; '));process.exit(1)}
console.log(`ACCEPT ${checks.length} CI worker invariants`);
