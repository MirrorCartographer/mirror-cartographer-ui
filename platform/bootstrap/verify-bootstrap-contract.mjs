import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const dir = path.dirname(fileURLToPath(import.meta.url));
const policy = JSON.parse(fs.readFileSync(path.join(dir, 'policy.json'), 'utf8'));
const inventory = JSON.parse(fs.readFileSync(path.join(dir, 'inventory.json'), 'utf8'));
const checks = [];
const require = (name, ok) => { if (!ok) throw new Error(`REJECT ${name}`); checks.push(name); };
require('project desired-state authority', policy.authority.canonical_desired_state === 'project-repository' && !policy.authority.provider_userdata_authoritative);
require('exportable desired state', policy.authority.exportable);
require('two-operator production changes', policy.authority.two_operator_production_changes);
require('stable project machine identity', policy.machine_identity.stable_project_id && !policy.machine_identity.provider_instance_id_authoritative);
require('hardware inventory', policy.machine_identity.hardware_inventory_recorded);
require('TPM not sole recovery', policy.machine_identity.tpm_optional_not_sole_recovery);
require('first-boot noninteractive bootstrap', policy.bootstrap.first_boot_only && policy.bootstrap.noninteractive);
require('offline bootstrap', policy.bootstrap.network_optional && policy.bootstrap.offline_bundle);
require('DNS-independent bootstrap', !policy.bootstrap.public_dns_required && !inventory.public_dns_required);
require('metadata-independent bootstrap', !policy.bootstrap.metadata_service_required && !inventory.metadata_service_required);
require('signed digest-verified configuration', policy.bootstrap.signed_configuration && policy.bootstrap.configuration_digest_verified);
require('no embedded bootstrap secrets', !policy.bootstrap.secrets_embedded);
require('pinned mirrored OS image', policy.operating_system.image_digest_pinned && policy.operating_system.image_mirrored);
require('verified boot', policy.operating_system.verified_boot_required);
require('transactional root', policy.operating_system.immutable_or_transactional_root);
require('A/B rollback', policy.operating_system.ab_updates && policy.operating_system.automatic_rollback && policy.operating_system.previous_image_retained);
require('security patch SLA', policy.operating_system.security_update_sla_days <= 7);
require('declarative idempotent configuration', policy.configuration.declarative && policy.configuration.idempotent);
require('drift detection', policy.configuration.drift_detection && policy.configuration.drift_fail_closed_for_security_controls);
require('mutation audit', policy.configuration.runtime_mutation_logged);
require('no boot-time package drift', !policy.configuration.package_install_during_boot);
require('no arbitrary remote scripts', !policy.configuration.arbitrary_remote_scripts);
require('bounded host overlays', policy.configuration.host_specific_overlays_bounded);
require('hardened remote access', !policy.access.ssh_password_auth && !policy.access.root_remote_login);
require('short-lived operator access', policy.access.short_lived_operator_credentials);
require('out-of-band and offline break-glass', policy.access.out_of_band_path && policy.access.break_glass_offline);
require('two-operator destructive reimage', policy.access.two_operator_destructive_reimage);
require('fresh signed rebuild evidence', policy.recovery.clean_host_rebuild_days <= 30 && policy.recovery.signed_evidence && inventory.last_clean_rebuild_days <= 30 && inventory.evidence_signed);
require('different hardware rebuild', policy.recovery.different_hardware_verified && inventory.different_hardware_verified);
require('provider-independent rebuild', policy.recovery.provider_independent_path && inventory.provider_independent_path);
require('offline image and config custody', policy.recovery.offline_image_copy && policy.recovery.offline_config_copy);
require('two bootstrap-key copies', policy.recovery.bootstrap_key_copies >= 2 && inventory.copies.keys.length >= 2);
require('complete machine evidence', Object.values(policy.evidence).every(v => v === true || (Number.isInteger(v) && v >= 2)));
console.log(`ACCEPT ${checks.length} bootstrap invariants`);
