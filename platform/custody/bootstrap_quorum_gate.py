#!/usr/bin/env python3
import hashlib, json, pathlib, re, sys
D=re.compile(r'^sha256:[0-9a-f]{64}$')
def cd(v): return 'sha256:'+hashlib.sha256(json.dumps(v,sort_keys=True,separators=(',',':')).encode()).hexdigest()
def stop(m): print(json.dumps({'status':'reject','reason':m})); raise SystemExit(1)
p=json.loads(pathlib.Path(sys.argv[1]).read_text())
u=dict(p); supplied=u.pop('plan_digest',None)
if p.get('schema')!='fia.bootstrap-quorum.v1': stop('schema')
if supplied!=cd(u): stop('digest')
q=p.get('quorum',{})
if q.get('shares',0)<5 or q.get('threshold',0)<3 or q['threshold']>=q['shares']: stop('quorum')
h=p.get('holders',[])
if len(h)!=q['shares'] or len({x['operator'] for x in h})<3 or len({x['failure_domain'] for x in h})<3: stop('independence')
if any(x.get('co_located') for x in h): stop('co-location')
if p.get('bootstrap',{}).get('initial_admin_revoked') is not True: stop('initial admin')
if p.get('drill',{}).get('result')!='pass' or p['drill'].get('independent_operators',0)<2: stop('drill')
b=p.get('backups',[])
if len(b)<3 or len({x['failure_domain'] for x in b})<2 or not any(x.get('offline_or_immutable') for x in b): stop('backups')
if not all(D.match(x.get('content_digest','')) for x in b): stop('backup digest')
print(json.dumps({'status':'accept','plan_digest':supplied},sort_keys=True))
