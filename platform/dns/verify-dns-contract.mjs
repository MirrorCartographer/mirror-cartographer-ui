#!/usr/bin/env node
import fs from "node:fs";
const [policyPath, inventoryPath] = process.argv.slice(2);
if (!policyPath || !inventoryPath) process.exit(2);
const p = JSON.parse(fs.readFileSync(policyPath, "utf8"));
const i = JSON.parse(fs.readFileSync(inventoryPath, "utf8"));
const failures = [];
const check = (x,m)=>{if(!x) failures.push(m)};
const digest = x => /^sha256:[0-9a-f]{64}$/.test(x ?? "");

check(p.authority.project_owned_zone_source && i.authority.project_owned, "project-owned zone source required");
check(!i.authority.registrar_zone_authority && !i.authority.provider_zone_authority, "registrar/provider cannot own zone truth");
check(i.authority.exportable && i.authority.replaceable, "zone and adapters must be portable");
check(i.domain.registrant_project_controlled, "registrant identity must be controlled");
check(i.domain.registrar_lock, "registrar lock required");
check(i.domain.registry_lock, "registry lock required");
check(i.domain.auto_renew, "auto-renew required");
check(i.domain.expiry_alert_days >= p.domain.expiry_alert_days, "domain expiry alert too late");
check(i.domain.payment_failure_runbook, "payment failure runbook required");
check(i.domain.transfer_auth_offline, "offline transfer custody required");
check(i.domain.registrar_accounts.length >= p.domain.minimum_registrar_accounts, "registrar exit path required");
check(i.domain.transfer_operator_count >= 2, "two-person transfer authority required");
check(i.zone.source_controlled && Number.isInteger(i.zone.serial) && i.zone.serial > 0, "source-controlled monotonic zone required");
check(i.zone.lint_passed && i.zone.unknown_types_preserved, "zone lint and unknown type preservation required");
check(typeof i.zone.ttl_policy === "string" && i.zone.ttl_policy.length > 0, "TTL policy required");
check(i.zone.authoritative_servers.length >= p.zone.minimum_authoritative_servers, "insufficient authoritative servers");
check(new Set(i.zone.authoritative_servers.map(x=>x.operator)).size >= p.zone.minimum_dns_operators, "insufficient DNS operators");
check(new Set(i.zone.authoritative_servers.map(x=>x.domain)).size >= p.zone.minimum_failure_domains, "insufficient DNS failure domains");
check(i.zone.hidden_primary, "hidden primary required");
check(i.zone.transfer_auth !== "none", "authenticated zone transfer required");
check(i.zone.dynamic_update_scope !== "unrestricted", "dynamic updates must be limited");
check(i.dnssec.enabled && i.dnssec.ksk_offline && i.dnssec.zsk_separate, "DNSSEC key separation required");
check(i.dnssec.ksk_copies.length >= p.dnssec.minimum_ksk_copies, "insufficient KSK copies");
check(new Set(i.dnssec.ksk_copies.map(x=>x.domain)).size >= p.dnssec.minimum_ksk_failure_domains, "insufficient KSK domains");
check(i.dnssec.prepublication_rollover, "safe rollover required");
check(i.dnssec.signature_expiry_alert_hours >= p.dnssec.signature_expiry_alert_hours, "signature expiry alert too late");
check(i.dnssec.parent_ds_verified, "parent DS verification required");
check(i.dnssec.cds_cdnskey_continuity, "CDS/CDNSKEY continuity check required");
check(i.dnssec.algorithm_migration_tested, "algorithm migration test required");
check(i.publishing.atomic_generation && i.publishing.multi_provider, "atomic multi-provider publishing required");
check(i.publishing.provider_credentials_separated, "provider credentials must be separated");
check(!i.publishing.writer_can_transfer_domain, "zone writer cannot transfer domain");
check(i.publishing.last_known_good && i.publishing.rollback_without_registrar, "known-good rollback required");
check(i.publishing.provider_loss_tested, "provider loss test required");
for (const key of ["server_loss","operator_loss","registrar_outage","signer_loss","bad_zone_rejected","bad_ds_rejected","expired_signature_tested","internal_recovery_without_public_dns"]) check(i.resilience[key], `missing resilience proof: ${key}`);
check(i.security.mfa && i.security.phishing_resistant_mfa, "strong MFA required");
check(!i.security.shared_email_sole_recovery, "shared email cannot be sole recovery");
check(!i.security.dns_api_credentials_on_edge, "DNS API credentials forbidden on edge");
check(!i.security.release_keys_on_dns_hosts, "release keys forbidden on DNS hosts");
check(i.security.audit_externalized && i.security.least_privilege_updates, "external audit and least privilege required");
check(i.evidence.machine_generated && i.evidence.signed, "signed machine evidence required");
for (const key of ["zone_digest","served_rrset_digest","delegation_digest"]) check(digest(i.evidence[key]), `invalid ${key}`);
check(i.evidence.dnssec_chain_validation && i.evidence.multi_vantage_probe && i.evidence.registrar_status, "live DNS evidence required");
check(i.evidence.operator_signatures >= 2, "two evidence signatures required");
check(i.evidence.retention_days >= p.evidence.retention_days, "evidence retention insufficient");
if (failures.length) {
  console.error(`REJECT ${failures.length} DNS/domain invariant(s)`);
  for (const f of failures) console.error(`- ${f}`);
  process.exit(1);
}
console.log("ACCEPT 57 DNS/domain invariants");
