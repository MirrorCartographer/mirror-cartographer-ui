import fs from 'node:fs';
import path from 'node:path';
const root = path.dirname(new URL(import.meta.url).pathname);
const policy = JSON.parse(fs.readFileSync(path.join(root,'policy.json'),'utf8'));
const inventory = JSON.parse(fs.readFileSync(path.join(root,'inventory.json'),'utf8'));
const checks=[];
const requireCheck=(name,ok)=>{checks.push({name,ok:Boolean(ok)});};
const a=policy.authority,t=policy.topology,d=policy.dns,s=policy.tls,c=policy.continuity,e=policy.evidence;
requireCheck('project ingress authority',a.project_controls_ingress_policy && a.provider_is_not_routing_authority);
requireCheck('replaceable DNS and CA',a.dns_provider_is_replaceable && a.public_ca_is_replaceable);
requireCheck('two ingress nodes',t.ingress_nodes>=2 && inventory.ingress_nodes.length>=2);
requireCheck('two failure domains',new Set(inventory.ingress_nodes.map(x=>x.failure_domain)).size>=2 && t.failure_domains>=2);
requireCheck('proxy-only ingress',t.reverse_proxy_only_public_ingress);
requireCheck('no public backend bind',t.backend_public_bind_forbidden && inventory.ingress_nodes.every(x=>!['0.0.0.0','::'].includes(x.backend_bind)));
requireCheck('health checks',t.health_checked_upstreams);
requireCheck('atomic reload',t.atomic_config_reload);
requireCheck('zone export',d.zone_exportable && inventory.dns.zone_export_format);
requireCheck('secondary DNS',d.secondary_authoritative_copy && inventory.dns.secondary);
requireCheck('registrar protection',d.registrar_lock_enabled && d.registry_lock_supported_or_documented);
requireCheck('DNSSEC recovery',d.dnssec_enabled && d.ds_recovery_documented);
requireCheck('bounded DNS TTL',d.ttl_seconds>0 && d.ttl_seconds<=900);
requireCheck('out-of-band origin',d.out_of_band_origin_access && inventory.dns.out_of_band_origin);
requireCheck('TLS floor',Number(s.minimum_version)>=1.2 && s.tls_1_3_enabled);
requireCheck('automatic renewal',s.automatic_renewal && s.renewal_window_days>=14);
requireCheck('issuer redundancy',s.two_acme_issuers && inventory.tls.issuers.length>=2);
requireCheck('ACME key separation',s.acme_account_key_separate_from_certificate_key);
requireCheck('ACME account recovery',s.acme_account_key_backed_up && inventory.tls.account_key_copies.length>=2);
requireCheck('persistent encrypted TLS storage',s.certificate_storage_persistent && s.certificate_storage_encrypted);
requireCheck('TLS storage redundancy',s.certificate_storage_not_single_host && inventory.tls.storage_copies.length>=2);
requireCheck('CAA issuer restriction',s.caa_restricts_issuers);
requireCheck('no unrestricted on-demand TLS',s.on_demand_tls_disabled);
requireCheck('private key permissions',s.private_key_permissions==='0600');
requireCheck('CA outage continuity',c.cached_unexpired_certificate_survives_ca_outage && c.proxy_restart_survives_ca_outage);
requireCheck('internal PKI path',c.local_internal_pki_available);
requireCheck('DNS-independent rollback',c.public_dns_not_required_for_rollback);
requireCheck('expiry alert',c.certificate_expiry_alert_days>=14 && c.certificate_expiry_alert_days<30);
requireCheck('external probes',c.dns_resolution_probed_externally && c.tls_handshake_probed_externally);
requireCheck('evidence digests',e.config_digest_recorded && e.dns_zone_digest_recorded);
requireCheck('chain verification',e.certificate_chain_verified);
requireCheck('signed failover evidence',e.failover_test_signed && inventory.evidence.signed);
requireCheck('two-operator root changes',e.two_operators_for_dns_or_tls_root_changes && new Set(inventory.evidence.operators).size>=2);
const failed=checks.filter(x=>!x.ok);
if(failed.length){for(const f of failed) console.error(`REJECT ${f.name}`); process.exit(1);}
console.log(`ACCEPT ${checks.length} network/TLS invariants`);
